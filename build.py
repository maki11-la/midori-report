#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ミドリ投資レポート・ビューアを生成する。

使い方:
    python3 build.py

reports.json にレポートを追加してから、上のコマンドで index.html と sw.js を再生成する。
画面の見た目は template.html、数字カードの取り出しは summary.py にある。
生成された index.html はダブルクリック（file://）でも閲覧できる。
https で公開したときは、初回訪問後にオフラインでも開ける。

reports.json の各要素:
    date            ISO日付 (例: "2026-11-21")
    title           見出し
    type            "日次" または "週まとめ"
    conclusion      サイドバー・タイムライン用の一行
                    （通常は結論の先頭1文。短い場合は2文まで）
    conclusion_full 結論の全文 (Markdown、省略可。無い場合は conclusion を使う)
                    markdown 内の「**結論:**」に続く本文から取る
    summary         (自動) build.py が本文から作る。reports.json には書かない
    markdown        レポート本文 (Markdown。文言・数字は変更しない)

新しいレポートを足す手順:
    1. reports.json の配列に、上の形のオブジェクトを追加する
    2. このフォルダで python3 build.py を実行する
       （公開分の更新は update.sh を使う）
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

from summary import summarize

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "reports.json"
OUT = ROOT / "index.html"
SW_OUT = ROOT / "sw.js"

ASSET_NAMES = (
    "manifest.json",
    "icon-180.png",
    "icon-192.png",
    "icon-512.png",
    "icon-512-maskable.png",
    "apple-touch-icon.png",
    "og.png",
)

TEMPLATE_FILE = ROOT / "template.html"
TEMPLATE = TEMPLATE_FILE.read_text(encoding="utf-8")

SW_TEMPLATE = "/* Generated by build.py — do not edit by hand. */\nconst CACHE = \"midori-viewer-__CACHE_VERSION__\";\nconst PRECACHE = [\n  \"./\",\n  \"./index.html\",\n  \"./manifest.json\",\n  \"./icon-180.png\",\n  \"./icon-192.png\",\n  \"./icon-512.png\",\n  \"./icon-512-maskable.png\",\n  \"./apple-touch-icon.png\",\n  \"./og.png\"\n];\n\nself.addEventListener(\"install\", function (event) {\n  event.waitUntil(\n    caches.open(CACHE).then(function (cache) {\n      return cache.addAll(PRECACHE);\n    }).then(function () {\n      return self.skipWaiting();\n    })\n  );\n});\n\nself.addEventListener(\"activate\", function (event) {\n  event.waitUntil(\n    caches.keys().then(function (keys) {\n      return Promise.all(keys.filter(function (key) {\n        return key !== CACHE;\n      }).map(function (key) {\n        return caches.delete(key);\n      }));\n    }).then(function () {\n      return self.clients.claim();\n    })\n  );\n});\n\nself.addEventListener(\"fetch\", function (event) {\n  const req = event.request;\n  if (req.method !== \"GET\") return;\n  const url = new URL(req.url);\n  if (url.origin !== self.location.origin) return;\n\n  event.respondWith((async function () {\n    const cache = await caches.open(CACHE);\n    const cached = await cache.match(req, { ignoreSearch: true });\n    const network = fetch(req).then(function (res) {\n      if (res && res.ok) cache.put(req, res.clone());\n      return res;\n    }).catch(function () {\n      return cached;\n    });\n    // Cache-first, then refresh the cache in the background.\n    if (cached) {\n      network.catch(function () {});\n      return cached;\n    }\n    return network;\n  })());\n});\n"

def embed_json(obj):
    s = json.dumps(obj, ensure_ascii=False, separators=(",", ":"))
    return (
        s.replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("&", "\\u0026")
        .replace("\u2028", "\\u2028")
        .replace("\u2029", "\\u2029")
    )


def load_reports():
    if not DATA.exists():
        sys.exit(f"reports.json が見つかりません: {DATA}")
    reports = json.loads(DATA.read_text(encoding="utf-8"))
    if not isinstance(reports, list):
        sys.exit("reports.json は配列である必要があります")
    required = {"date", "title", "type", "conclusion", "markdown"}
    for i, r in enumerate(reports):
        missing = required - set(r)
        if missing:
            sys.exit(f"reports.json[{i}] に不足しています: {', '.join(sorted(missing))}")
    reports.sort(key=lambda r: r["date"], reverse=True)
    return reports


def cache_version(*blobs: bytes) -> str:
    h = hashlib.sha256()
    for blob in blobs:
        h.update(blob)
        h.update(b"\0")
    if DATA.exists():
        h.update(DATA.read_bytes())
    h.update(b"\0")
    h.update(TEMPLATE.encode("utf-8"))
    for name in ASSET_NAMES:
        path = ROOT / name
        if path.exists():
            h.update(name.encode("utf-8"))
            h.update(path.read_bytes())
    return h.hexdigest()[:12]


def write_sw(version: str) -> None:
    SW_OUT.write_text(
        SW_TEMPLATE.replace("__CACHE_VERSION__", version),
        encoding="utf-8",
        newline="\n",
    )


def build():
    reports = load_reports()
    # 「今日の一言」「短い結論」「数字カード」は本文から毎回自動で作る (reports.json は変更しない)
    embedded = [dict(r, summary=summarize(r)) for r in reports]
    html = TEMPLATE.replace("__REPORTS_JSON__", embed_json(embedded))
    OUT.write_text(html, encoding="utf-8", newline="\n")
    version = cache_version(html.encode("utf-8"))
    write_sw(version)
    print(f"Wrote {OUT} ({OUT.stat().st_size:,} bytes, {len(reports)} reports)")
    print(f"Wrote {SW_OUT} (cache midori-viewer-{version})")
    if reports:
        print(f"Date range: {reports[-1]['date']} — {reports[0]['date']}")


if __name__ == "__main__":
    build()
